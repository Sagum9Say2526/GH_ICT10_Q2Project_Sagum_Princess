def identify_element(event=None):
    # this gets what the user typed, remove spaces, and fixes the capitals automatically
    symbol = document.getElementById("symbol").value.strip().capitalize()
    # if the symbol isn't in the dictionary u just get blanks back
    name, number, mass = elements.get(symbol, ("", "", ""))
    # True means the element was found, False means its not there
    found = symbol in elements
    messages = {
        True: f"<b>Element Symbol:</b> {symbol}<br>"
              f"<b>Element Name:</b> {name}<br>"
              f"<b>Atomic Number:</b> {number}<br>"
              f"<b>Atomic Mass:</b> {mass}",
        False: f"<b>{symbol}</b> is not an element symbol.",
    }
    document.getElementById("result").innerHTML = messages[found]